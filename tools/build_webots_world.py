"""City JSON + scenario -> Webots world (.wbt) with the DEF names WebotsBackend expects.

    uv run python tools/build_webots_world.py scenarios/demo.yaml webots/worlds/demo.wbt

Base nodes only (no EXTERNPROTO), so the world loads with no network. Buildings are boxes
fitted to each footprint's minimum rotated rectangle; the real LoD2 meshes replace them later
as long as the DEF names (DRONE_<id>, SRC_<id>, RIG) stay. Drone visuals are scaled up x8 so
they are visible at city scale.
"""

import math
import sys
from itertools import pairwise
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from shapely import Polygon

from earshot.backend.webots import LIVE_SLOTS, live_slot
from earshot.city import City
from earshot.scenario import Scenario

DRONE_SCALE = 8
SOURCE_LOOK = {  # class -> (colour, box size for non-drones)
    "DRONE": ("1 0.2 0.3", None),
    "VEHICLE": ("1 0.7 0.2", "10 3 3"),
    "TRAIN": ("0.7 0.5 0.3", "60 3.5 4"),
    "NOTHING": ("0.6 0.6 0.6", "2 2 1.5"),  # nuisance: a rooftop fan / AC unit
}


def pbr(rgb, rough=0.9):
    return f"PBRAppearance {{ baseColor {rgb} roughness {rough} metalness 0 }}"


def box(name_def, x, y, z, w, d, h, yaw, rgb, extra=""):
    return (
        f"{name_def}Pose {{ translation {x:.2f} {y:.2f} {z:.2f} rotation 0 0 1 {yaw:.4f} "
        f"children [ Shape {{ appearance {pbr(rgb)} geometry Box {{ size {w:.2f} {d:.2f} {h:.2f} }} }} ] {extra}}}"
    )


def fitted_box(poly: Polygon):
    rect = poly.minimum_rotated_rectangle
    pts = list(rect.exterior.coords)[:4]
    e1 = (pts[1][0] - pts[0][0], pts[1][1] - pts[0][1])
    e2 = (pts[2][0] - pts[1][0], pts[2][1] - pts[1][1])
    c = rect.centroid
    return c.x, c.y, math.hypot(*e1), math.hypot(*e2), math.atan2(e1[1], e1[0])


def segments(line_pts, width, z, rgb):
    out = []
    for (x0, y0), (x1, y1) in pairwise(line_pts):
        length = math.hypot(x1 - x0, y1 - y0)
        out.append(box("", (x0 + x1) / 2, (y0 + y1) / 2, z, length, width, 0.1,
                       math.atan2(y1 - y0, x1 - x0), rgb))
    return out


def drone_shape(rgb):
    s = DRONE_SCALE
    arms = " ".join(
        f"Pose {{ translation {0.18 * s * dx} {0.18 * s * dy} 0.03 children [ Shape {{ "
        f"appearance {pbr('0.15 0.15 0.15')} geometry Cylinder {{ radius {0.1 * s} height {0.01 * s} }} }} ] }}"
        for dx, dy in [(1, 1), (1, -1), (-1, 1), (-1, -1)]
    )
    body = f"Shape {{ appearance {pbr(rgb, 0.5)} geometry Box {{ size {0.3 * s} {0.2 * s} {0.08 * s} }} }}"
    return f"{body} {arms}"


def main(scenario_path: str, out_path: str) -> None:
    sc = Scenario.load(scenario_path)
    city = City.load(sc.city)
    x0, y0, x1, y1 = city.bounds
    perch = {p.building for p in city.perch_sites}
    parts = [
        "#VRML_SIM R2025a utf8",
        f"# generated by tools/build_webots_world.py from {scenario_path} -- do not edit by hand",
        'WorldInfo { info [ "Earshot" ] basicTimeStep 20 }',
        (
            f"Viewpoint {{ orientation 0 1 0 1.5708 position {(x0 + x1) / 2:.0f} "
            f"{(y0 + y1) / 2:.0f} {1.3 * max(x1 - x0, y1 - y0):.0f} far 10000 }}"
        ),
        "Background { skyColor [ 0.62 0.72 0.85 ] }",
        "DirectionalLight { direction -0.4 -0.3 -1 intensity 2.5 castShadows FALSE }",
        box("", (x0 + x1) / 2, (y0 + y1) / 2, -0.05, x1 - x0, y1 - y0, 0.1, 0, "0.32 0.36 0.30"),
    ]
    for b in city.buildings:
        cx, cy, w, d, yaw = fitted_box(b.footprint)
        rgb = "0.55 0.6 0.68" if b.id in perch else "0.62 0.6 0.58"
        parts.append(box("", cx, cy, b.height / 2, w, d, b.height, yaw, rgb))
    for r in city.roads:
        parts += segments(list(r.coords), 8, 0.06, "0.2 0.2 0.22")
    for r in city.rails:
        parts += segments(list(r.coords), 4, 0.08, "0.45 0.33 0.2")

    for d in sc.drones:
        parts.append(f"DEF DRONE_{d.id} Pose {{ translation {d.x} {d.y} 40 children [ "
                     f"{drone_shape('0.2 0.5 0.95')} ] }}")

    # scripted sources, plus spare slots that live (hotkey) sources are shown in
    slots = [(s.id, s.cls.name) for s in sc.sources] + [
        (live_slot(cls, k), cls) for cls in SOURCE_LOOK for k in range(LIVE_SLOTS)
    ]
    for sid, cls in slots:
        rgb, box_size = SOURCE_LOOK[cls]
        geom = (drone_shape(rgb) if cls == "DRONE" else
                f"Shape {{ appearance {pbr(rgb)} geometry Box {{ size {box_size} }} }}")
        parts.append(f'DEF SRC_{sid} Solid {{ translation 0 0 -100 name "src_{sid}" '
                     f"recognitionColors [ {rgb} ] children [ {geom} ] }}")

    parts.append(
        'DEF RIG Robot { translation 0 0 -100 name "supervisor" supervisor TRUE '
        'controller "<extern>" children [ Pose { rotation 0 1 0 0.6 children [ '
        'Camera { name "camera" width 400 height 240 far 1000 '
        "recognition Recognition { maxRange 300 segmentation TRUE } } ] } ] }"
    )
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text("\n".join(parts) + "\n")
    print(f"{out_path}: {len(city.buildings)} buildings, {len(sc.drones)} drones, "
          f"{len(sc.sources)} sources")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "scenarios/demo.yaml",
         sys.argv[2] if len(sys.argv) > 2 else "webots/worlds/demo.wbt")
